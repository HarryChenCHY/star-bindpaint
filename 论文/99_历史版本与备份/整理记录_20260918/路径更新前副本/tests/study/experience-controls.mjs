import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const out = '论文/交互简化与研究码验收';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000);
  await page.goto('http://localhost:3001/');
  assert.equal(await page.getByRole('button', { name: '开始第一幅', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '看看怎么画', exact: true }).count(), 0);
  await page.getByRole('button', { name: '产品介绍', exact: true }).waitFor();
  await page.screenshot({ path: out + '/首页.png' });
  await page.goto('http://localhost:3001/create');
  await page.getByRole('tab', { name: /上传图片/ }).click();
  const png = await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 256; c.height = 256;
    const x = c.getContext('2d'); x.fillStyle = 'white'; x.fillRect(0, 0, 256, 256);
    x.fillStyle = '#7ca599'; x.fillRect(30, 30, 190, 150); x.fillStyle = '#ffe073'; x.fillRect(80, 150, 80, 65);
    return c.toDataURL().split(',')[1];
  });
  await page.locator('input[type=file]').setInputFiles({ name: '合成练习.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.getByRole('button', { name: '生成星迹并开始' }).waitFor();
  assert.equal(await page.getByText('引导强度', { exact: true }).count(), 0);
  assert.equal(await page.getByText('笔触颗粒度', { exact: true }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: out + '/手机选图.png', fullPage: true });
  await page.getByRole('button', { name: '生成星迹并开始' }).click();
  await page.getByRole('button', { name: '完整', exact: true }).waitFor({ timeout: 30000 });
  assert.equal(await page.evaluate(() => sessionStorage.getItem('star-bindpaint-roughness')), '1');
  const reference = page.getByRole('button', { name: '全屏查看参考原图', exact: true });
  assert.equal(await page.getByRole('img', { name: '参考原图', exact: true }).getAttribute('src'), await page.evaluate(() => sessionStorage.getItem('star-bindpaint-source')));
  const pixels = await page.locator('canvas').first().evaluate(c => c.toDataURL());
  await reference.click();
  const preview = page.getByRole('dialog', { name: '参考原图全屏预览' });
  await preview.waitFor();
  assert.equal(Math.round((await preview.boundingBox()).width), 390);
  await page.screenshot({ path: out + '/手机原图全屏.png' });
  await page.keyboard.press('Escape');
  assert.equal(await preview.isVisible(), false);
  await reference.click();
  await page.getByRole('button', { name: '点击原图恢复到提示卡' }).click();
  assert.equal(await preview.isVisible(), false);
  assert.equal(await page.locator('canvas').first().evaluate(c => c.toDataURL()), pixels);
  await page.getByTestId('floating-companion').screenshot({ path: out + '/参考原图提示卡.png' });
  const brush = page.getByRole('button', { name: '星光画笔', exact: true });
  assert.match((await brush.innerText()).trim(), /^\d+$/);
  await brush.click();
  assert.match((await page.getByText('大小', { exact: true }).locator('..').innerText()).replace(/\s/g, ''), /^大小\d+$/);
  await brush.click();
  await page.getByRole('button', { name: '收起月亮伙伴', exact: true }).click();
  await page.screenshot({ path: out + '/手机箭头引导.png' });
  await page.getByRole('button', { name: '展开月亮伙伴', exact: true }).click();
  await page.getByRole('button', { name: '自由星域', exact: true }).click();
  assert.equal(await page.getByText('选择一颗自由星愿', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /不设主题|换主题/ }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '完整', exact: true }).count(), 0);
  const box = await page.locator('canvas.paint-canvas').boundingBox();
  await page.mouse.move(box.x + box.width * .3, box.y + box.height * .4);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .6, box.y + box.height * .6, { steps: 12 });
  await page.mouse.up();
  const before = await page.locator('canvas').first().evaluate(c => c.toDataURL());
  await page.screenshot({ path: out + '/手机自由星域.png' });
  await page.getByRole('button', { name: '沿星迹', exact: true }).click();
  await page.getByRole('button', { name: '完整', exact: true }).waitFor();
  assert.equal(await page.locator('canvas').first().evaluate(c => c.toDataURL()), before);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.evaluate(() => {
    sessionStorage.setItem('star-bindpaint-free-style', 'vangogh');
    sessionStorage.setItem('star-bindpaint-difficulty', 'free');
    sessionStorage.removeItem('star-bindpaint-source');
  });
  await page.reload();
  await page.getByRole('button', { name: '自由星域', exact: true }).waitFor();
  assert.equal(await page.getByText('选择一颗自由星愿', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /不设主题|换主题/ }).count(), 0);
  await page.locator('canvas.paint-canvas').waitFor();
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.waitForURL('**/create');
  console.log('PASS: 首页、默认细笔完整引导、手机自由绘画往返切换与作品保留');
} finally { await browser.close(); }
